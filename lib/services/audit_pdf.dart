import 'dart:typed_data';

import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;

import '../models/audit_entry.dart';
import '../utils/format.dart';

// The built-in PDF font has no arrow glyph
String _safe(String s) => s.replaceAll('→', '->');

Future<Uint8List> buildAuditPdf({
  required List<AuditEntry> entries,
  required String periodLabel,
  required String generatedBy,
}) async {
  final doc = pw.Document(title: 'BOOKSLOT Audit Log');

  final rows = entries.map((e) {
    final actor = e.actorName.isEmpty ? e.actorEmail : e.actorName;
    final hasName = (e.targetName ?? '').isNotEmpty;
    final target = e.targetEmail == null
        ? '-'
        : (hasName ? '${e.targetName}\n${e.targetEmail}' : e.targetEmail!);
    return [
      e.createdAt == null ? '-' : formatDateTime(e.createdAt!),
      _safe('$actor\n(${e.actorRole})'),
      auditActionTitle(e.action),
      _safe(target),
      _safe(e.details ?? ''),
    ];
  }).toList();

  doc.addPage(
    pw.MultiPage(
      pageFormat: PdfPageFormat.a4.landscape,
      margin: pw.EdgeInsets.all(28),
      footer: (ctx) => pw.Align(
        alignment: pw.Alignment.centerRight,
        child: pw.Text(
          'Page ${ctx.pageNumber} of ${ctx.pagesCount}',
          style: pw.TextStyle(fontSize: 8),
        ),
      ),
      build: (ctx) => [
        pw.Text(
          'BOOKSLOT - Audit Log',
          style: pw.TextStyle(fontSize: 20, fontWeight: pw.FontWeight.bold),
        ),
        pw.SizedBox(height: 4),
        pw.Text(
          'Granby Colleges Mobile Library System',
          style: pw.TextStyle(fontSize: 10),
        ),
        pw.SizedBox(height: 10),
        pw.Text('Period: $periodLabel', style: pw.TextStyle(fontSize: 10)),
        pw.Text(
          'Entries: ${entries.length}',
          style: pw.TextStyle(fontSize: 10),
        ),
        pw.Text(
          _safe(
            'Generated by: $generatedBy on ${formatDateTime(DateTime.now())}',
          ),
          style: pw.TextStyle(fontSize: 10),
        ),
        pw.SizedBox(height: 12),
        pw.TableHelper.fromTextArray(
          headers: ['Date & time', 'Done by', 'Action', 'Account', 'Details'],
          data: rows,
          headerStyle: pw.TextStyle(
            fontSize: 8,
            fontWeight: pw.FontWeight.bold,
          ),
          cellStyle: pw.TextStyle(fontSize: 8),
          headerDecoration: pw.BoxDecoration(color: PdfColors.grey300),
          cellAlignment: pw.Alignment.topLeft,
          cellPadding: pw.EdgeInsets.all(4),
          border: pw.TableBorder.all(color: PdfColors.grey500, width: 0.5),
          columnWidths: {
            0: pw.FixedColumnWidth(88),
            1: pw.FlexColumnWidth(2),
            2: pw.FlexColumnWidth(2),
            3: pw.FlexColumnWidth(2.2),
            4: pw.FlexColumnWidth(3),
          },
        ),
      ],
    ),
  );

  return doc.save();
}
